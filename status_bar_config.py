"""status_bar_config.py - segment selection for the Claude Code status bar.

The status bar is assembled from independently selectable *segments* (model,
context window, rate limits, diff count, total cost). Which segments
appear is chosen at install time by the component-based installer, which writes
the selection to a config file next to the installed modules. At render time
this module reports which segments are enabled so unselected ones are omitted.

Design contract:
  - When **no** config file exists, ``enabled_segments`` returns ``None``,
    meaning "show every segment". This keeps manual installs and the in-repo
    source tree (which ship no config) rendering the full bar unchanged.
  - When a config file exists, only the valid segment ids it lists are enabled;
    an empty file therefore yields an empty bar. Unknown or malformed entries
    are skipped (and logged at debug level), so a hand-edited or partially
    written file can never crash the status line.

The file format is one segment id per line; ``#`` comments and blank lines are
ignored. The installer regenerates this file on every run, so re-running it with
a different ``--select`` is the supported way to change the bar.

Components:
  - SEGMENT_IDS: Canonical ordered tuple of every known segment id.
  - enabled_segments: Resolve the enabled segment ids (or ``None`` for all).
  - is_segment_enabled: Report whether a single segment id should render.
  - main: CLI used by install.sh to initialize/extend the config file.
"""

from __future__ import annotations

import os
import sys

from status_bar_logging import get_logger, log_call

logger = get_logger(__name__)

# Canonical segment ids, in bar order. Kept in sync with the render registry in
# status_bar_render.py and the installer manifest in installer/components.sh.
SEGMENT_IDS: tuple[str, ...] = (
    "model",
    "context",
    "five_hour",
    "weekly",
    "diff",
    "tokens",
    "cost",
)

# Config file name, resolved next to this module so it travels with the installed
# copy in ~/.claude as well as the in-repo source tree.
_CONFIG_FILE_NAME = "claude-status-bar.conf"

_CONFIG_HEADER = (
    "# claude-status-bar.conf - status-bar segment selection.\n"
    "#\n"
    "# Generated by install.sh. One enabled segment id per line; '#' comments\n"
    "# and blank lines are ignored. Re-run the installer (optionally with\n"
    "# --select id,id,...) to change which segments appear.\n"
    f"# Known ids, in bar order: {', '.join(SEGMENT_IDS)}.\n"
)


def _config_path() -> str:
    """Return the absolute path of the segment-selection config file.

    Returns:
        str: ``<module-dir>/claude-status-bar.conf`` -- the single location the
        renderer reads and the installer writes, beside the installed modules.
    """
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), _CONFIG_FILE_NAME)


@log_call(logger)
def enabled_segments() -> set[str] | None:
    """Resolve which status-bar segments are enabled.

    Returns:
        set[str] | None: ``None`` when no config file exists (render every
        segment); otherwise the set of valid segment ids listed in the file.
        Unknown ids are dropped and logged at debug level.
    """
    path = _config_path()
    try:
        raw = open(path, encoding="utf-8").read()
    except FileNotFoundError:
        logger.debug("no segment config at %s; enabling all segments", path)
        return None
    except OSError as exc:
        logger.warning("could not read segment config %s: %r; enabling all", path, exc)
        return None

    enabled: set[str] = set()
    for line in raw.splitlines():
        token = line.split("#", 1)[0].strip()
        if not token:
            continue
        if token in SEGMENT_IDS:
            enabled.add(token)
        else:
            logger.debug("ignoring unknown segment id in config: %r", token)
    return enabled


def is_segment_enabled(segment_id: str, enabled: set[str] | None) -> bool:
    """Report whether a segment should render given a resolved selection.

    Args:
        segment_id: Segment id to check.
        enabled: Result of :func:`enabled_segments`; ``None`` means "all".

    Returns:
        bool: ``True`` when the segment should render.
    """
    return enabled is None or segment_id in enabled


@log_call(logger)
def _write_config(path: str, ids: list[str]) -> None:
    """Write the config header followed by the given valid segment ids.

    Args:
        path: Destination config-file path.
        ids: Segment ids to enable, written in canonical bar order. Unknown ids
            are dropped with a warning so a typo can never poison the file.

    Returns:
        None.
    """
    valid = [seg for seg in SEGMENT_IDS if seg in ids]
    for unknown in (set(ids) - set(SEGMENT_IDS)):
        logger.warning("refusing to write unknown segment id: %r", unknown)
    body = "".join(f"{seg}\n" for seg in valid)
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(_CONFIG_HEADER)
        handle.write(body)
    logger.info("wrote %d segment(s) to %s: %s", len(valid), path, valid)


@log_call(logger)
def main(argv: list[str] | None = None) -> int:
    """CLI used by the installer to manage the segment-selection config.

    Sub-commands (all operate on the config beside this module, or an explicit
    path passed as the final argument):

      ``init``        Create the file with the header and **no** segments. The
                      core installer calls this first so segment components can
                      append themselves into a known-clean file.
      ``enable ID``   Append segment ``ID`` if valid and not already present.

    Args:
        argv: Argument list excluding the program name; defaults to
            ``sys.argv[1:]``.

    Returns:
        int: ``0`` on success; ``2`` on a usage or validation error.
    """
    args = list(sys.argv[1:] if argv is None else argv)
    if not args:
        print("Usage: status_bar_config.py {init|enable ID} [config_path]", file=sys.stderr)
        return 2

    command = args[0]
    if command == "init":
        path = args[1] if len(args) > 1 else _config_path()
        _write_config(path, [])
        return 0
    if command == "enable":
        if len(args) < 2:
            print("Usage: status_bar_config.py enable ID [config_path]", file=sys.stderr)
            return 2
        seg = args[1]
        if seg not in SEGMENT_IDS:
            print(f"Unknown segment id: {seg}", file=sys.stderr)
            return 2
        path = args[2] if len(args) > 2 else _config_path()
        current = enabled_segments() if path == _config_path() else _read_ids(path)
        ids = list(current or [])
        if seg not in ids:
            ids.append(seg)
        _write_config(path, ids)
        return 0

    print(f"Unknown command: {command}", file=sys.stderr)
    return 2


def _read_ids(path: str) -> set[str]:
    """Read valid segment ids from an explicit config path (CLI helper)."""
    try:
        raw = open(path, encoding="utf-8").read()
    except OSError:
        return set()
    return {tok for line in raw.splitlines()
            if (tok := line.split("#", 1)[0].strip()) in SEGMENT_IDS}


if __name__ == "__main__":
    raise SystemExit(main())
